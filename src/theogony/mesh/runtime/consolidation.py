# A tag is a candidate *name* only if it is capitalised in the source and rare
# enough to discriminate. The first half is what the extractor gives us: it
# writes type tags in lower case (`concept` on 2,799 founding-mesh nodes,
# `paragraph_concept` on 829) and names in upper case.
#
# The second half is a guard rather than the instrument, and the measurement says
# so plainly. Sweeping the ceiling on the founding mesh:
#
#     DF<=4    117 proposals
#     DF<=8    142
#     DF<=12   147
#     DF<=25   147      <- the default
#     DF<=100  147
#
# **It is inert above 12 here.** What actually removes the categorical tags is
# elsewhere: excluding paragraph concepts (which took `Greek mythology`'s 23
# false proposals with it) and keeping digits in a name (which stopped
# `Fragment #3` and `Fragment #37` from being one name). Both are category
# judgements about what a node *is*; a frequency threshold is neither, and
# tuning one to do their job would have hidden the reason.
#
# It stays because a substrate can carry a capitalised tag on thousands of nodes
# — `data/mesh-wiki-100k` is seeded from Wikidata, where type labels are
# capitalised — and one such tag would put every node carrying it into a single
# adjudication fan-out. 25 is a ceiling on the damage, not a decision about
# identity: the adjudicator makes those.
DEFAULT_MAX_NAME_DF = 25

# Below two nodes a name proposes nothing, by definition.
_MIN_NAME_DF = 2

# Tags on a merged node, most-evidenced first. The union of six Zeus nodes runs
# to a dozen names; the substrate's compression discipline applies to tags as
# much as to descriptions (`MESH_SUBSTRATE.md` §"Field discipline" point 4), and
# `assemble_constellation` reads only the first eight anyway.
_MAX_MERGED_TAGS = 12

# What a regenerated description may cost. Doctrine: "typically ~200-500 chars,
# and never a stored paragraph body".
MAX_DESCRIPTION_CHARS = 400


def normalise_name(raw: str | None) -> str:
    """Fold a name to its comparable core, **keeping digits**.

    The evaluator's fold (`eval/corpus_qa._normalise`) strips them, because it is
    matching a gold name against a corpus that carries inline footnote markers —
    a node is called `Hestia 1618` as readily as `Hestia`. Identity cannot afford
    the same licence: with digits stripped, `Fragment #3` and `Fragment #37` are
    one name, and so are `Berlin Papyri 9739` and `Berlin Papyri 10560`. Those are
    numbered things whose number *is* their identity.

    Measured on the founding mesh: 63 of 2,453 capitalised tags contain a digit
    and every one of them is a citation label — no entity name is disambiguated by
    a numeral here, so keeping them costs nothing and prevents that whole class of
    false grouping.
    """
    text = re.sub(r"[^a-z0-9\s]", " ", (raw or "").lower())
    return re.sub(r"\s+", " ", text).strip()


def description_head(node: ConsolidatedNode) -> str:
    """The name a reader sees — everything before the em dash (PHX-1065)."""
    return (node.description or "").split("—")[0].strip()


@dataclass(frozen=True)
class MergeProposal:
    """One candidate absorption: ``member`` may be the same entity as ``anchor``."""

    anchor_id: str
    member_id: str
    name: str
    signal: str
    shared_names: tuple[str, ...]
    description_score: float
    context_score: float


@dataclass(frozen=True)
class MergeVerdict:
    proposal: MergeProposal
    decision: str  # "same" | "different" | "uncertain"
    reason: str = ""

    @property
    def same(self) -> bool:
        return self.decision == "same"


@dataclass
class ConsolidationResult:
    """What one pass did, in the shape the audit record and the CLI both want."""

    nodes_before: int = 0
    nodes_after: int = 0
    edges_before: int = 0
    edges_after: int = 0
    proposals: int = 0
    adjudicated: int = 0
    verdict_counts: dict[str, int] = field(default_factory=dict)
    clusters_merged: int = 0
    nodes_absorbed: int = 0
    ambiguous_dropped: int = 0
    self_edges_dropped: int = 0
    edges_coalesced: int = 0
    descriptions_regenerated: int = 0
    description_fallbacks: int = 0
    # Which model settled these identities. Recorded on the result as well as in
    # the audit so that an exported pass can be replayed with its provenance
    # intact — a consolidation is a decision about what the substrate *is*, and
    # "some model, once" is not an answer to who made it.
    adjudicator_model: str = ""
    describer_model: str = ""
    audit_id: str | None = None
    dry_run: bool = False

    def as_detail(self) -> dict[str, Any]:
        return {
            "nodes_before": self.nodes_before,
            "nodes_after": self.nodes_after,
            "edges_before": self.edges_before,
            "edges_after": self.edges_after,
            "proposals": self.proposals,
            "adjudicated": self.adjudicated,
            "verdicts": dict(self.verdict_counts),
            "clusters_merged": self.clusters_merged,
            "nodes_absorbed": self.nodes_absorbed,
            "ambiguous_dropped": self.ambiguous_dropped,
            "self_edges_dropped": self.self_edges_dropped,
            "edges_coalesced": self.edges_coalesced,
            "descriptions_regenerated": self.descriptions_regenerated,
            "description_fallbacks": self.description_fallbacks,
            "adjudicator_model": self.adjudicator_model,
            "describer_model": self.describer_model,
        }



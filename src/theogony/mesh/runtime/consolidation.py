"""Oneiros consolidation — merging entity candidates and regenerating what they say.

This is the load-bearing half of migration step S5 (`MESH_MIGRATION_PLAN.md`
§"Step S5"), and it exists because of a measurement rather than a plan.

`MESH_SUBSTRATE.md` §"Why two tiers" specifies **eager-when-clear,
emergent-when-not**: Kadmos links a reference to an existing Tier-1 node when
Q-ID, description or tag evidence decides it, and otherwise attaches a fresh
**entity candidate** (`is_candidate = True`) whose identity Oneiros settles
later. The second half was never built. On the founding mesh the consequence is
literal: **every one of the 3,783 entity nodes carries `is_candidate = True`**,
and Zeus is six of them —

    Zeus                     — King of the gods, son of Cronos, aegis-holder.
    son of Cronos            — Zeus, the king of the gods, who freed the Hecatoncheires.
    her father               — Zeus, the father of Persephone, who is called the Son of Cronos.
    father of men and gods   — Zeus, who speaks to the Hecatoncheires after they are freed.
    Son of Chronos           — A reference to Zeus, who granted frogs their dual nature.
    (a paragraph concept tagged Zeus and Thetis)

Two costs follow, and they are different costs. The evidence for one entity is
**split across several nodes**, so no node accumulates the potential its entity
earned; and the name a reader sees is the name of whichever *mention* created
the node, which is why a Constellation answering "who are the children of Cronus
and Rhea" showed `her father`, `Host of Many`, `dear mother` and `Vesta`
(PHX-1096). Merging fixes both at once: it is the same operation.

**What this module does not do.** S5 as specified is consolidation *plus* splits,
renormalisation, the pruner, pathology surveillance, therapy and three-factor RL.
This is consolidation only. Tier promotion (Tier 1 -> 2 -> 3) is specified as
earned through "number of distinct activation contexts, age, breadth of incoming
references" — and `fired_total` is **0 on every node in the substrate**, because
nothing on the read path increments it. Promotion would therefore be promotion by
age alone, so it is not implemented here; see PHX-1097 for the finding.

**Why an LLM decides the merges.** Tag evidence alone over-merges, and the
substrate itself shows how: the node `Daughter of Cronos — A goddess, daughter of
Cronos, likely Athena or Hestia` is tagged with *both* names. Any rule that
merges on a shared discriminating tag fuses Athena into Hestia. Doctrine puts a
small LLM call inside consolidation already (`MESH_SUBSTRATE.md` §"Consolidation
— promoting Tier 0 -> Tier 1": "a description regenerated by a small LLM call"),
and this is the same call answering the prior question. It is **not** an
insertion-time gate — the substrate's forbidden pre-gate is a `False` before a
chunk enters (§"What the substrate deliberately does not do", point 1). This runs
post-hoc over accumulated evidence, which is exactly where doctrine puts
identity decisions.

Structure of a pass:

    propose   cheap, pure substrate bookkeeping, no network  -> MergeProposal
    adjudicate  one small LLM call per proposal              -> MergeVerdict
    apply     rewire edges, fuse nodes, write the audit      -> ConsolidationResult
    regenerate  one small LLM call per surviving cluster     -> new description

Each stage is separately callable and separately testable, and `propose` alone is
a useful read-only report on how fragmented a substrate's identity is.
"""

